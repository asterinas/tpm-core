use crate::{
    cmd::{
        CC_CONTEXT_LOAD, CC_CONTEXT_SAVE, CC_FLUSH_CONTEXT, CC_GET_CAPABILITY, CC_GET_RANDOM,
        CC_PCR_EXTEND, CC_PCR_READ, CC_SELF_TEST, CC_SHUTDOWN, CC_STARTUP,
    },
    msg::TPM_HEADER_LEN,
    phy::TisPhy,
    rewrite::read_be32,
    tis::{budget_of, TisErr},
    tis_core::Tis,
};

pub const RC_SUCCESS: u32 = 0x0000_0000;
/// Base address of warning-class return codes. Bit 11 set means “not a failure; it is temporarily not
/// possible to do this.”
pub const RC_WARN_BASE: u32 = 0x0000_0900;
/// The device is self-testing and the requested functionality is not yet ready.
pub const RC_TESTING: u32 = 0x0000_090A;
/// The device is busy; retry the same command later.
pub const RC_RETRY: u32 = 0x0000_0922;
/// The device yielded control and did not execute the command. Semantically similar to [`RC_RETRY`],
/// but triggered by the device’s scheduling policy rather than resource exhaustion; retrying once usually
/// succeeds.
pub const RC_YIELDED: u32 = 0x0000_0908;
/// Initial backoff duration, in milliseconds.
const RETRY_FIRST_MS: u32 = 20;
/// Upper bound for a single backoff duration, in milliseconds.
const RETRY_CAP_MS: u32 = 2000;
/// Maximum retry count. If a retryable return code remains after this number, pass it through directly to
/// the caller — this layer does not translate “still busy after waiting so long” into an error, because
/// that is a judgment the caller must make.
const RETRY_MAX: u32 = 8;
const DURATION_SHORT_MS: u32 = 750;
const DURATION_MEDIUM_MS: u32 = 2000;
const DURATION_LONG_MS: u32 = 30000;
/// Default upper bound for commands not listed above. It is intentionally large: if this layer does not
/// recognize a command, it has no basis for saying how fast it should be.
const DURATION_DEFAULT_MS: u32 = 120000;
/// Command code → upper bound on execution time, in milliseconds.
///
/// The return value is always positive, so the polling budget computed by [`budget_of`] is always non-zero.
fn duration_ms(cc: u32) -> u32 {
    if cc == CC_STARTUP
        || cc == CC_SHUTDOWN
        || cc == CC_PCR_READ
        || cc == CC_PCR_EXTEND
        || cc == CC_GET_CAPABILITY
        || cc == CC_CONTEXT_LOAD
        || cc == CC_CONTEXT_SAVE
        || cc == CC_FLUSH_CONTEXT
    {
        DURATION_SHORT_MS
    } else if cc == CC_GET_RANDOM {
        DURATION_MEDIUM_MS
    } else if cc == CC_SELF_TEST {
        DURATION_LONG_MS
    } else {
        DURATION_DEFAULT_MS
    }
}
/// Command code → polling budget for waiting for a response.
pub fn poll_budget(cc: u32) -> u32 {
    budget_of(duration_ms(cc))
}
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum XferErr {
    /// Transport-layer error. The bytes did not complete a full round trip.
    Bus(TisErr),
    /// The command is invalid as a command: the length field does not match the buffer. No bytes of the
    /// command are sent.
    BadCommand,
}
/// Read a big-endian u32 while exposing both protocol encodings in one value.
///
/// The packet header is generated by the command layer (using the additive form specified by the protocol),
/// while the handle area is read by the rewrite layer (using shifts or the equivalent). This layer spans
/// both, reading once to expose both forms and avoid forcing each call site to re-derive the bridge lemma.
pub(crate) fn peek_be32(b: &[u8], off: usize) -> u32 {
    read_be32(b, off)
}
fn cmd_wf(cmd: &[u8], len: usize) -> bool {
    if len < TPM_HEADER_LEN {
        return false;
    }
    if len > cmd.len() {
        return false;
    }
    let d = peek_be32(cmd, 2);
    d as usize == len
}
/// The response body (everything after the header) is not shorter than `min_body`.
///
/// This exists as the **last gate before parsing**: the parser functions assume “sufficient body length” as
/// a precondition, and if this gate is not closed, out-of-bounds reads would become the caller’s
/// responsibility instead of a hidden implementation detail of the parser.
pub fn body_at_least(n: usize, min_body: usize) -> bool {
    n - TPM_HEADER_LEN >= min_body
}
pub struct Xfer<P: TisPhy> {
    pub tis: Tis<P>,
    /// Remaining retry budget. It is stored as a field rather than a constant because the boot phase (device
    /// just powered on, self-test not complete) and the steady state use the same code but require different
    /// patience.
    pub retries: u32,
}
impl<P: TisPhy> Xfer<P> {
    pub fn new(tis: Tis<P>) -> Self {
        Xfer {
            tis,
            retries: RETRY_MAX,
        }
    }
    /// Runtime self-check: whether the state satisfies the prerequisite for sending a command.
    ///
    /// This exists because of the interface boundary — this layer is called by an interface without
    /// preconditions (the signature is chosen by the higher-level verification requirements and cannot be
    /// changed), while its own methods have preconditions. The gap must be closed at runtime: check once,
    /// and if the preconditions are not met, return immediately rather than continuing with invalid state.
    pub fn ready(&self) -> bool {
        self.tis.locality < crate::tis::MAX_LOCALITY && !self.tis.held
    }
    /// Wait `ticks` polling intervals.
    ///
    /// This uses integer multiples of the polling interval as the wait length rather than accepting a sleep
    /// interface: this layer does not introduce a time concept, and the actual waiting duration is determined
    /// by the physical layer’s throttling. The termination of this loop therefore comes directly from the
    /// counter.
    fn backoff(&mut self, ticks: u32) {
        let mut left = ticks;
        while left > 0 {
            self.tis.phy.delay();
            left -= 1;
        }
    }
    /// Send a command, receive a response, and extract the return code.
    ///
    /// The return code is read from a fixed offset in the response header, and its value does not depend on
    /// parsing the packet body — the transport layer guarantees the response length is at least one header,
    /// so this read is unconditional.
    ///
    /// `exec_budget` is forwarded directly to [`Tis::transmit`] to bound the number of polling iterations
    /// spent waiting for `STS_DATA_AVAIL`.
    fn attempt(
        &mut self,
        cmd: &[u8],
        len: usize,
        rsp: &mut [u8],
        exec_budget: u32,
    ) -> Result<(usize, u32), XferErr> {
        let n = self
            .tis
            .transmit(cmd, len, rsp, exec_budget)
            .map_err(XferErr::Bus)?;
        let rc = peek_be32(&*rsp, 6);
        Ok((n, rc))
    }
    /// Retryable return codes.
    ///
    /// A self-test command encountering “still self-testing” is an exception: that command asks for exactly
    /// the self-test state, and “still testing” is a valid answer rather than a response to avoid. Treating it
    /// as retryable turns a simple status query into a blocking wait, which is especially wrong during the
    /// boot phase.
    pub fn retryable(rc: u32, cc: u32) -> bool {
        if rc == RC_RETRY || rc == RC_YIELDED {
            true
        } else if rc == RC_TESTING {
            cc != CC_SELF_TEST
        } else {
            false
        }
    }
    /// Send a command, retry it if necessary, and return the response length and return code.
    ///
    /// Three properties are fixed in the signature:
    ///
    /// - **No byte is sent if the command has not passed self-test**. Malformed commands are rejected here,
    ///   and the device never sees them.
    /// - **Locality is never held across any exit path**. The transport layer guarantees this iteratively, and
    ///   retries simply chain the guarantee — each attempt is a complete acquire/release cycle rather than
    ///   holding locality in a loop. Waiting a few more milliseconds to free locality for the rest of the
    ///   wait is worth it.
    /// - **The return code is exactly the value in the response header**. This layer does not rewrite,
    ///   swallow, or translate it; if the retry count is exhausted but the return code is still retryable, it
    ///   is passed through unchanged.
    ///
    /// Retrying is safe because the command buffer is read-only: the layer receives an immutable slice and
    /// never mutates it, so the bytes sent on the second attempt are identical to the first, byte for byte.
    /// If the send and receive shared a single buffer, this would not hold; before retrying, the original
    /// text would have to be restored. That is a bug that is easy to miss and difficult to notice after the
    /// fact; using separate buffers avoids it entirely.
    pub fn run(&mut self, cmd: &[u8], len: usize, rsp: &mut [u8]) -> Result<(usize, u32), XferErr> {
        if !cmd_wf(cmd, len) {
            return Err(XferErr::BadCommand);
        }
        let cc = peek_be32(cmd, 6);
        let exec_budget = poll_budget(cc);
        let cap = budget_of(RETRY_CAP_MS);
        let mut ticks = budget_of(RETRY_FIRST_MS);
        let mut left = self.retries;
        while left > 0 {
            match self.attempt(cmd, len, rsp, exec_budget) {
                Ok((n, rc)) => {
                    if !Self::retryable(rc, cc) {
                        return Ok((n, rc));
                    }
                }
                Err(e) => return Err(e),
            }
            self.backoff(ticks);
            if ticks < cap {
                if ticks <= cap - ticks {
                    ticks += ticks;
                } else {
                    ticks = cap;
                }
            }
            left -= 1;
        }
        self.attempt(cmd, len, rsp, exec_budget)
    }
}
